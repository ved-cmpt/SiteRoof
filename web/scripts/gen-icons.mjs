// Generates src/app/shared/icons.generated.ts from @material-symbols/svg-400 (Apache-2.0).
// Only the icons listed here ship in the bundle. Run: node scripts/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const names = [
  'construction', 'dashboard', 'apartment', 'fact_check', 'history', 'admin_panel_settings', 'menu', 'close',
  'arrow_forward', 'arrow_back', 'check_circle', 'warning', 'error', 'info', 'block', 'schedule', 'event',
  'person', 'group', 'swap_horiz', 'restart_alt', 'logout', 'add', 'edit', 'comment', 'link', 'link_off',
  'inventory_2', 'local_shipping', 'sync', 'cloud_done', 'cloud_off', 'search', 'filter_list', 'flag',
  'trending_up', 'verified', 'lock', 'lock_open', 'playlist_add_check', 'chevron_right', 'keyboard_arrow_down', 
  'open_in_new', 'shield', 'code', 'database', 'checklist', 'engineering', 'hourglass_top', 'help',
  'task_alt', 'radio_button_unchecked', 'rule', 'refresh', 'map', 'location_on', 'tune',
];

const entries = names.map((name) => {
  const svg = readFileSync(new URL(`../node_modules/@material-symbols/svg-400/outlined/${name}.svg`, import.meta.url), 'utf8');
  const paths = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`No path in ${name}`);
  return `  ${name}: ${JSON.stringify(paths.join(' '))},`;
});

writeFileSync(
  new URL('../src/app/shared/icons.generated.ts', import.meta.url),
  `// Generated by scripts/gen-icons.mjs from @material-symbols/svg-400 (Apache-2.0). Do not edit.\n` +
    `export const ICONS = {\n${entries.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`Wrote ${names.length} icons`);
